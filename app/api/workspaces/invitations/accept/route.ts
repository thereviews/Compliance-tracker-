import { NextResponse } from 'next/server';
import { createHash } from 'node:crypto';
import { getAuthClient, supabaseAdmin } from '@/lib/supabase';

export const dynamic = 'force-dynamic';

function jsonError(message: string, status: number) {
  return NextResponse.json({ error: message }, { status });
}

export async function POST(req: Request) {
  try {
    // Authenticate the caller.
    const authHeader = req.headers.get('Authorization');

    if (!authHeader?.startsWith('Bearer ')) {
      return jsonError('You must sign in to accept an invitation', 401);
    }

    const supabase = getAuthClient(authHeader);

    const {
      data: { user },
      error: authError,
    } = await supabase.auth.getUser();

    if (authError || !user) {
      return jsonError('Your session is invalid. Please sign in again.', 401);
    }

    // Require a verified email address.
    if (!user.email || !user.email_confirmed_at) {
      return jsonError(
        'Please verify your email address before accepting an invitation',
        403
      );
    }

    // Parse and validate the request.
    let body: unknown;

    try {
      body = await req.json();
    } catch {
      return jsonError('Invalid JSON request body', 400);
    }

    if (!body || typeof body !== 'object' || Array.isArray(body)) {
      return jsonError('Invalid request body', 400);
    }

    const input = body as Record<string, unknown>;
    const token = input.token;

    // Tokens generated by randomBytes(32).toString('base64url') are
    // 43 characters long. Never accept a token hash from the browser.
    if (
      typeof token !== 'string' ||
      !/^[A-Za-z0-9_-]{43}$/.test(token)
    ) {
      return jsonError('A valid invitation token is required', 400);
    }

    // Only the token hash is looked up in the database.
    const tokenHash = createHash('sha256')
      .update(token)
      .digest('hex');

    // The database function validates and accepts the invitation
    // atomically, including checking email, expiry, and membership.
    const { data, error } = await supabaseAdmin.rpc(
      'accept_workspace_invitation',
      {
        p_token_hash: tokenHash,
        p_user_id: user.id,
        p_user_email: user.email,
      }
    );

    if (error) {
      console.error('INVITATION ACCEPTANCE DATABASE ERROR');
      return jsonError('Could not process this invitation', 500);
    }

    if (!data || typeof data !== 'object' || Array.isArray(data)) {
      return jsonError('Unexpected invitation response', 500);
    }

    const result = data as {
      success?: boolean;
      code?: string;
      workspace_id?: string;
      role?: string;
    };

    if (result.success === true) {
      return NextResponse.json({
        success: true,
        message: 'Invitation accepted successfully',
        workspaceId: result.workspace_id,
        role: result.role,
      });
    }

    switch (result.code) {
      case 'invalid_invitation':
        return jsonError('This invitation does not exist or is invalid', 404);

      case 'invalid_or_expired':
        return jsonError(
          'This invitation has expired or is no longer valid',
          410
        );

      case 'email_mismatch':
        return jsonError(
          'Sign in with the email address that received the invitation',
          403
        );

      case 'already_member':
        return jsonError('You are already a member of this workspace', 409);

      case 'invalid_workspace':
        return jsonError('This invitation is no longer valid', 400);

      default:
        console.error('INVITATION ACCEPTANCE RETURNED AN UNKNOWN RESULT');
        return jsonError('Could not accept this invitation', 500);
    }
  } catch (error: unknown) {
    console.error(
      'INVITATION ACCEPTANCE API ERROR:',
      error instanceof Error ? error.message : 'Unknown error'
    );

    return jsonError('Could not accept this invitation', 500);
  }
}
